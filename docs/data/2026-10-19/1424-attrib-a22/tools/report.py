"""EXPERIMENT (exp/attrib-a22). Tables of the journal entry.

  python3 report.py RUNS_DIR OUTDIR        writes OUTDIR/{runs.csv,boots.csv,tables.md}
"""
import os
import sys

import numpy as np
import pandas as pd

from analyze import CELLS, K_IPI_US, fmt, md, med, pair, pair_table, summ
from parse import load_runs

KEY = ["label", "cfg", "rep"]
AMP = {  # state: (repeats per call, unit: 'hook' per hook call, 'entry' per fragment entry, 'one' per request)
    "ampcr": (256, "hook"), "amplk": (32, "hook"), "ampsr": (64, "hook"), "amppan": (64, "entry"),
    "ampbr": (16, "one"), "ampat": (16, "hook"), "amptr": (64, "entry"),
    "amplink": (64, "chain"), "ampcl": (64, "chain"),
}
AMP_NAME = {
    "ampcr": "kjit_can_run (per hook call)", "amplk": "kjit_lookup (per hook call)", "ampsr": "SRCU lock+unlock (per hook call)",
    "ampat": "relaxed atomic add (the stats counters)", "amppan": "msr pan #0/#1 pair (per fragment entry)",
    "amptr": "asm trampoline round trip into a stub (per fragment entry)",
    "amplink": "chain exit: label search + publish of kjit_frag_link (per chained entry)",
    "ampcl": "chain exit: publish of the linked lookup (per chained entry)", "ampbr": "FP/SIMD bracket: neon begin/load/save/end (per bracket)",
}


def slope_ns(runs, state, cfg):
    N, unit = AMP[state]
    r = runs[runs.cfg == cfg]
    on = r[r.state == "on"]
    per = {"hook": on.hook_calls_pr.median(), "entry": on.fragment_entries_pr.median(), "one": on.fpsimd_entries_pr.median(),
           "chain": on.chains_pr.median()}[unit]
    d = pair(r, state, "on", "cpu_us")
    if d.empty:
        return None, per
    d = d.assign(d=d["d"] * 1000.0 / (N * per))
    return summ(d), per


def per_req(runs, cfg, state, col):
    r = runs[(runs.cfg == cfg) & (runs.state == state)][col].dropna()
    return float(np.median(r)) if len(r) else np.nan


def main(runs_dir, outdir):
    runs, boots = load_runs(runs_dir)
    os.makedirs(outdir, exist_ok=True)
    runs.to_csv(f"{outdir}/runs.csv", index=False)
    boots.to_csv(f"{outdir}/boots.csv", index=False)
    out = []
    P = out.append
    P("# Tables (generated by tools/report.py)\n")
    b = boots[["label", "kpti", "load1_before", "load1_after"]].copy()
    b["runs"] = [int((runs.label == l).sum()) for l in b.label]
    P("## Boots\n")
    P(md(b.set_index("label")))
    for kpti in (0, 1):
        kr = runs[runs.kpti == kpti]
        if kr.empty:
            continue
        kn = "KPTI forced on" if kpti else "KPTI off"
        P(f"\n# {kn}\n")
        cfgs_all = [c for c in CELLS if c in set(kr.cfg)]
        # 1. gap
        rows = {}
        for typ, name in (("H", "plain module"), ("P", "plain module, pipelined cells"), ("A", "instrumented, A boots"),
                          ("D", "instrumented, D boots"), ("N", "instrumented, N boots")):
            r = kr[kr.type == typ]
            if r.empty:
                continue
            rows[f"on - off, {name}"] = {c: fmt(summ(pair(r[r.cfg == c], "on", "off", "cpu_us"))) for c in cfgs_all}
            rows[f"off, {name} (us per request, median)"] = {c: f"{med(r, 'off', 'cpu_us', c):.3f}" for c in cfgs_all}
            rows[f"on, {name} (us per request, median)"] = {c: f"{med(r, 'on', 'cpu_us', c):.3f}" for c in cfgs_all}
        # pooled over every boot that has both states (any module), with a cluster bootstrap of the median (boots, then pairs)
        rng = np.random.default_rng(1)
        pooled, pooled_ci = {}, {}
        for c in cfgs_all:
            d = pair(kr[kr.cfg == c], "on", "off", "cpu_us")
            pooled[c] = fmt(summ(d))
            if len(d) and d.label.nunique() > 1:
                groups = [g["d"].values for _, g in d.groupby("label")]
                meds = []
                for _ in range(5000):
                    pick = rng.integers(0, len(groups), len(groups))
                    meds.append(np.median(np.concatenate([rng.choice(groups[i], len(groups[i])) for i in pick])))
                lo, hi = np.percentile(meds, [2.5, 97.5])
                pooled_ci[c] = f"[{lo:+.3f}..{hi:+.3f}]"
            else:
                pooled_ci[c] = "-"
        rows["on - off, pooled over all boots with both states"] = pooled
        rows["  95% cluster-bootstrap CI of that median"] = pooled_ci
        P(f"\n## {kn}: the gap, on - off, us of server CPU per request, median [Q1..Q3] (boots positive / boots, pairs)\n")
        P(md(pd.DataFrame(rows).T.rename_axis("")))
        # 2. pairs (instrumented)
        ir = kr[kr.type.isin(["A", "D", "N"])]
        if ir.empty:
            continue
        cfgs = [c for c in CELLS if c in set(ir.cfg)]
        specs = {
            "svcn - on  (entry/exit saved, plus svcn's own wake-ups)": ("svcn", "on"),
            "decl1 - off (hook + can_run, all code native)": ("decl1", "off"),
            "decl2 - decl1 (+ lookup)": ("decl2", "decl1"),
            "decl2 - off": ("decl2", "off"),
            "svcn - off": ("svcn", "off"),
            "onT - on (timers' own cost)": ("onT", "on"),
            "offT - off": ("offT", "off"),
            "offS - off (SCHED_IDLE spinner on CPU 0)": ("offS", "off"),
            "onS - on": ("onS", "on"),
            "onS - offS (the gap with a CPU 0 that never idles)": ("onS", "offS"),
        }
        P(f"\n## {kn}: instrumented-module pairs, us per request\n")
        P(md(pair_table(ir, specs, cfgs)))
        # 3. counters
        cols = ["hook_calls_pr", "syscalls_in_kernel_pr", "fragment_entries_pr", "fpsimd_entries_pr", "chains_pr", "exit_svc_pr",
                "exit_bl_pr", "exit_blr_pr", "exit_br_pr", "exit_ret_pr", "exit_mem_pr", "exit_unsupported_pr", "exit_budget_pr",
                "run_declined_pr", "svc_declined_pr", "ibtc_miss_cold_pr", "ibtc_miss_conflict_pr", "ibtc_miss_other_pr",
                "ibtc_fpsimd_boundary_pr"]
        P(f"\n## {kn}: runtime counters per request, state `on` (median over runs)\n")
        P(md(pd.DataFrame({c: [f"{per_req(ir, c0, 'on', c):.4f}" for c0 in cfgs] for c in cols}, index=cfgs).T.rename_axis("counter")))
        # 4. amplifiers
        rows = {}
        for st in AMP:
            row = {}
            for c in cfgs:
                s, per = slope_ns(ir, st, c)
                row[c] = f"{s['med']:.2f} [{s['q1']:.2f}..{s['q3']:.2f}] ns x {per:.3f} = {s['med'] * per / 1000:.4f} us" if s else "-"
            rows[AMP_NAME[st]] = row
        P(f"\n## {kn}: amplifiers, in-situ cost of one repetition, ns [Q1..Q3] x repetitions per request = us per request\n")
        P(md(pd.DataFrame(rows).T.rename_axis("")))
        # 5. timers
        tcols = [("t_hook_us", "hook calls (whole)"), ("c_logic_us", "hook logic, corrected"), ("c_plain_us", "plain runs, corrected"),
                 ("c_fp_us", "FP/SIMD runs, corrected"), ("c_bracket_us", "bracket ops, corrected"), ("c_gsys_us", "in-kernel gaps (corrected; contain epoll sleeps)")]
        rows = {}
        for st in ("onT",):
            for col, name in tcols:
                rows[f"{st}: {name}"] = {c: f"{per_req(ir, c, st, col):.3f}" for c in cfgs}
            rows[f"{st}: hook calls / FP bracket entries per request"] = {
                c: f"{per_req(ir, c, st, 't_hook_pr'):.3f} / {per_req(ir, c, st, 't_ffp_pr'):.3f}" for c in cfgs}
        if "c_prep_us" in ir.columns and ir["c_prep_us"].notna().any():
            for col, name in (("c_prep_us", "prep: hook entry -> first run (can_run, lookup, accessors; FP-first: + bracket front)"),
                              ("c_chain_us", "chain: run end -> next run start (exit handling, ibtc probe, link/lookup; + bracket front)"),
                              ("c_post_us", "post: last run end -> hook return (SVC exit handling, stats; + bracket back)")):
                rows[f"onT: {name}"] = {c: f"{per_req(ir, c, 'onT', col):.3f}" for c in cfgs}
                pr = col.replace("_us", "_pr")
                rows[f"onT:   ns per occurrence, count per request"] = rows.get(f"onT:   ns per occurrence, count per request", {})
                rows[f"onT:   {col[2:-3]} ns x per request"] = {
                    c: f"{per_req(ir, c, 'onT', col) * 1000.0 / per_req(ir, c, 'onT', pr):.1f} x {per_req(ir, c, 'onT', pr):.3f}" for c in cfgs}
            rows.pop("onT:   ns per occurrence, count per request", None)
        P(f"\n## {kn}: timers of onT, us per request (median over runs)\n")
        P(md(pd.DataFrame(rows).T.rename_axis("")))
        # 6. budget
        rows = {}
        for c in cfgs:
            r = ir[ir.cfg == c]
            G = summ(pair(r, "on", "off", "cpu_us"))
            Gm = G["med"] if G else np.nan
            F1 = per_req(r, c, "onT", "c_plain_us") + per_req(r, c, "onT", "c_fp_us")
            Br = per_req(r, c, "onT", "c_bracket_us")
            Lg = per_req(r, c, "onT", "c_logic_us")
            hk = per_req(r, c, "on", "hook_calls_pr")
            sr, _ = slope_ns(r, "ampsr", c)
            Sr = (sr["med"] * hk / 1000.0) if sr else np.nan
            d = pair(r, "off", "on", "user_us")
            U0 = d["d"].median() if not d.empty else np.nan
            sv = pair(r, "svcn", "on", "cpu_us")["d"].median()
            wk = pair(r, "svcn", "on", "ipi_cl_k")["d"].median() * K_IPI_US / 1000.0
            sc = pair(r, "on", "off", "ipi_cl_k")["d"].median() * K_IPI_US / 1000.0
            sumv = F1 - U0 + Br + Lg - (sv - wk) + sc  # SRCU: the off state calls the hook too (module loaded, enable=0) and pays it as well
            rows[c] = {
                "fragment code in the kernel (timers, plain + FP runs)": f"{F1:+.3f}",
                "native EL0 code that no longer runs (off user ticks - on user ticks)": f"{-U0:+.3f}",
                "= translated code net of native": f"{F1 - U0:+.3f}",
                "FP/SIMD bracket (timers)": f"{Br:+.3f}",
                "hook logic: can_run, lookup, run_chain, stats (timers)": f"{Lg:+.3f}",
                "memo, not in the sum: SRCU lock/unlock of the hook (paid by off as well)": f"({Sr:.3f})",
                "syscall entry/exit saved (svcn - on, minus svcn's extra wake-ups)": f"{-(sv - wk):+.3f}",
                "remote wake-ups of the load generator (IPI on CPUs 1-3, on - off, x 6.9 us)": f"{sc:+.3f}",
                "sum": f"{sumv:+.3f}",
                "measured on - off (instrumented, paired)": f"{Gm:+.3f}",
                "residual (measured - sum)": f"{Gm - sumv:+.3f}",
            }
        P(f"\n## {kn}: budget, us per request, on - off\n")
        P(md(pd.DataFrame(rows).rename_axis("")))
        # 5b. timer lines with their spread over the onT runs
        rows = {}
        for col, name in (("c_logic_us", "hook logic proper"), ("c_bracket_us", "FP/SIMD bracket"), ("c_plain_us", "plain fragment runs"),
                          ("c_fp_us", "FP/SIMD fragment runs"), ("c_prep_us", "prep"), ("c_chain_us", "chain (incl. bracket front)"),
                          ("c_post_us", "post (incl. bracket back)")):
            row = {}
            for c in cfgs:
                v = ir[(ir.cfg == c) & (ir.state == "onT")][col].dropna()
                nb = ir[(ir.cfg == c) & (ir.state == "onT") & ir[col].notna()].label.nunique()
                row[c] = f"{v.median():.3f} [{v.quantile(.25):.3f}..{v.quantile(.75):.3f}] ({len(v)} runs, {nb} boots)" if len(v) else "-"
            rows[name] = row
        P(f"\n## {kn}: timer lines of onT, us per request, median [Q1..Q3] over runs\n")
        P(md(pd.DataFrame(rows).T.rename_axis("")))
        # 6b. budget v2: independent measurements only (no tick-based native time)
        P_CELL = {"ug": "ugp16", "us": "usp16", "up": "ugp16"}
        RUN_NS = 14.8  # trampoline 8.0 + prologue/epilogue/loop 6.8 ns per fragment run, hot (micro boots, x_rep_call slope)
        rows = {}
        for c in cfgs:
            r = ir[ir.cfg == c]
            Gh = summ(pair(kr[(kr.type == "H") & (kr.cfg == c)], "on", "off", "cpu_us"))
            Gm = Gh["med"] if Gh else np.nan
            Lg = per_req(r, c, "onT", "c_logic_us")
            Br = per_req(r, c, "onT", "c_bracket_us")
            ent = per_req(r, c, "on", "fragment_entries_pr")
            Ru = RUN_NS * ent / 1000.0
            pc = P_CELL[c]
            Pp = summ(pair(runs[(runs.kpti == 0) & (runs.type == "P") & (runs.cfg == pc)], "on", "off", "cpu_us"))
            Bd = Pp["med"] if Pp else np.nan
            sv = summ(pair(r, "svcn", "on", "cpu_us"))
            Sv = sv["med"] if sv else np.nan
            sumv = Lg + Br + Ru + Bd - Sv
            rows[c] = {
                "hook logic proper: can_run, lookup, run_chain, exit handling, stats (timers)": f"{Lg:+.3f}",
                "FP/SIMD bracket incl. its two CNTVCT stat reads (timers)": f"{Br:+.3f}",
                "run entry/exit: trampoline, PAN pair, prologue, epilogue (14.8 ns hot x entries)": f"{Ru:+.3f}",
                "translated body above native at steady state (pipelined -P 16 gap, plain module, KPTI off)": f"{Bd:+.3f}",
                "entry/exit and native cold start saved (svcn - on)": f"{-Sv:+.3f}",
                "sum": f"{sumv:+.3f}",
                "measured on - off, plain module": f"{Gm:+.3f}",
                "residual (measured - sum): protocol feedback, noise, unmeasured": f"{Gm - sumv:+.3f}",
            }
        P(f"\n## {kn}: budget v2, us per request, on - off (independent measurements; the -P 16 line is a KPTI-off measurement in both tables)\n")
        P(md(pd.DataFrame(rows).rename_axis("")))
        # 6c. final decomposition: hot-unit saving (101 ns per syscall; KPTI on: + the null-syscall difference 207.3 - 133.3 ns, assumed)
        SAVE_NS = {"ug": 100.5, "us": 103.4, "up": 100.5}
        KPTI_EXTRA_NS = (207.3 - 133.3) if kpti else 0.0
        rows = {}
        for c in cfgs:
            r = ir[ir.cfg == c]
            Gh = summ(pair(kr[(kr.type == "H") & (kr.cfg == c)], "on", "off", "cpu_us"))
            Gp = summ(pair(kr[kr.cfg == c], "on", "off", "cpu_us"))
            Lg = per_req(r, c, "onT", "c_logic_us")
            Br = per_req(r, c, "onT", "c_bracket_us")
            ent = per_req(r, c, "on", "fragment_entries_pr")
            hk = per_req(r, c, "on", "hook_calls_pr")
            Ru = RUN_NS * ent / 1000.0
            Bd = summ(pair(runs[(runs.kpti == 0) & (runs.type == "P") & (runs.cfg == P_CELL[c])], "on", "off", "cpu_us"))["med"]
            Sv = (SAVE_NS[c] + KPTI_EXTRA_NS) * hk / 1000.0
            ip = pair(r, "on", "off", "ipi_cl_k")["d"].median() * K_IPI_US / 1000.0
            sumv = Lg + Br + Ru + Bd - Sv
            rows[c] = {
                "1. entry/exit avoided: in-kernel syscalls x hot unit": f"{-Sv:+.3f}  ({hk:.2f} x {SAVE_NS[c] + KPTI_EXTRA_NS:.0f} ns)",
                "   in situ, svcn - on (protocol-polluted)": fmt(summ(pair(r, "svcn", "on", "cpu_us"))),
                "2. hook logic proper (timers)": f"{Lg:+.3f}",
                "3. FP/SIMD bracket (timers)": f"{Br:+.3f}",
                "4. run entry/exit (hot unit 14.8 ns x entries)": f"{Ru:+.3f}  ({ent:.2f} entries)",
                "5. translated body above native, steady state (-P 16 gap)": f"{Bd:+.3f}",
                "6. intrinsic sum 1+2+3+4+5": f"{sumv:+.3f}",
                "7. wake-up IPIs sent to the load generator, on - off, x 6.9 us": f"{ip:+.3f}",
                "8. measured on - off, plain module": fmt(Gh),
                "   measured on - off, pooled over all boots": fmt(Gp),
                "9. residual 8 - 6 (closed loop, saving model, noise)": f"{Gh['med'] - sumv:+.3f}",
            }
        P(f"\n## {kn}: decomposition of on - off, us per request (final form)\n")
        P(md(pd.DataFrame(rows).rename_axis("")))
        # 7. scheduling
        cols = [("cpu_us", "cpu us/req"), ("rps", "req/s"), ("nvol_k", "blocks/1000"), ("ninv_k", "involuntary/1000"),
                ("ipi_cl_k", "wake IPIs sent (rx on CPUs 1-3)/1000"), ("ipi_c0_k", "IPIs rx CPU 0 /1000"), ("c0_idle_frac", "CPU 0 idle fraction")]
        if "ev_eventloop_cycles" in ir.columns:
            ir = ir.assign(ev_cycles_k=ir["ev_eventloop_cycles"] * 1000.0 / ir["n"])
            cols.append(("ev_cycles_k", "event-loop cycles/1000 req"))
        for c in cfgs:
            rows = {}
            for st in ["off", "on", "offS", "onS", "offT", "onT", "svcn", "decl2"] + [s for s in sorted(set(ir.state)) if "D" in s and s[:3] in ("off", "onD") or s.startswith("offD")]:
                if st not in set(ir[ir.cfg == c].state):
                    continue
                rows[st] = {name: f"{per_req(ir, c, st, col):.3f}" if col not in ("rps",) else f"{per_req(ir, c, st, col):.0f}" for col, name in cols}
            P(f"\n## {kn}: scheduling, {CELLS[c]} (median over runs of the state)\n")
            P(md(pd.DataFrame(rows).T.rename_axis("state")))
        # 8. D states: dose-response of the protocol to a known slow-down, in either state
        if any(st.startswith(("offD", "onD")) for st in set(ir.state)):
            for c in cfgs:
                rows = {}
                hk = per_req(ir, c, "on", "hook_calls_pr")
                for a, b in (("offD100", "off"), ("offD300", "off"), ("onD100", "on"), ("onD300", "on"), ("on", "off"),
                             ("onD100", "off"), ("onD300", "off"), ("onD100", "offD100"), ("onD300", "offD300")):
                    if a not in set(ir[ir.cfg == c].state):
                        continue
                    row = {}
                    inj = 0.0
                    for st, sg in ((a, 1), (b, -1)):
                        if "D" in st:
                            inj += sg * float(st[st.index("D") + 1:]) * 0.325 * hk / 1000.0
                    row["injected us/req (D x 0.325 ns x hook calls)"] = f"{inj:+.3f}"
                    dc = summ(pair(ir[ir.cfg == c], a, b, "cpu_us"))
                    row["realized fraction of the injection"] = f"{(dc['med'] / inj):.2f}" if inj else "-"
                    for col, name, d in (("cpu_us", "cpu us/req", 3), ("nvol_k", "blocks/1000", 2), ("ipi_cl_k", "wake IPIs/1000", 2),
                                         ("c0_idle_frac", "CPU 0 idle", 3), ("rps", "req/s", 0)):
                        row[name] = fmt(summ(pair(ir[ir.cfg == c], a, b, col)), d, pos=False)
                    rows[f"{a} - {b}"] = row
                if rows:
                    P(f"\n## {kn}: x_delay dose-response, {CELLS[c]} (paired, median [Q1..Q3]); one iteration = 0.325 ns per hook call\n")
                    P(md(pd.DataFrame(rows).T.rename_axis("pair")))
        if any(st.startswith("nostats") for st in set(ir.state)):
            specs = {f"{st} - on": (st, "on") for st in sorted(set(ir.state)) if st.startswith("nostats")}
            P(f"\n## {kn}: statistics ablation (x_nostats: 1 runtime counter updates, 2 hook_calls per-CPU add, 4 bracket CNTVCT reads), us per request\n")
            P(md(pair_table(ir, specs, cfgs)))
    open(f"{outdir}/tables.md", "w").write("\n".join(out))
    return runs, boots, out


if __name__ == "__main__":
    runs, boots, out = main(sys.argv[1], sys.argv[2])
    print("\n".join(out))
